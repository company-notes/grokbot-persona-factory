export class Localization {
  readonly defaultLocale: Locale = "zh-hant";
  private readonly dictionaries: Record<Locale, Dictionary> = { en, "zh-hant": zhHant, "zh-hans": zhHans };

  normalize(value?: string): Locale {
    if (!value) {
      return this.defaultLocale;
    }
    const normalized = value.toLowerCase();
    if (["zh-tw", "zh-hk", "zh-hant"].includes(normalized)) {
      return "zh-hant";
    }
    if (["zh-cn", "zh-sg", "zh-hans"].includes(normalized)) {
      return "zh-hans";
    }
    if (normalized === "en" || normalized.startsWith("en-")) {
      return "en";
    }
    throw new ValidationError("locale must be en, zh-hant or zh-hans");
  }

  messages(locale: Locale): Dictionary {
    return this.dictionaries[locale];
  }

  translate(locale: Locale, key: string): string {
    const value = this.dictionaries[locale][key];
    if (value === undefined) {
      throw new Error(`Missing ${locale} translation: ${key}`);
    }
    return value;
  }
}
